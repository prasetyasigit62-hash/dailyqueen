function resolveFloorId(floorName?: string) {
    const value = floorName?.toLowerCase() || '';

    if (value.includes('ground') || value.includes('gf')) {
        return 'gf';
    }

    if (value.includes('1st') || value.includes('first') || value.includes('lantai 1') || value.includes('f1')) {
        return 'f1';
    }

    if (value.includes('2nd') || value.includes('second') || value.includes('lantai 2') || value.includes('f2')) {
        return 'f2';
    }

    if (value.includes('3rd') || value.includes('third') || value.includes('lantai 3') || value.includes('f3')) {
        return 'f3';
    }

    return 'gf';
}


function normalizeMapName(value?: string) {
    return (value || '')
        .toLowerCase()
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .replace(/[^a-z0-9]+/g, ' ')
        .trim();
}

function getMapConfig(floorId: string): MapConfig {
    if (floorId === 'gf') {
        return GF_MAP_CONFIG;
    }

    if (floorId === 'f2') {
        return SECOND_F_MAP_CONFIG;
    }

    if (floorId === 'f3') {
        return THIRD_F_MAP_CONFIG;
    }

    return ONE_F_MAP_CONFIG;
}

function getMapTenantMarker(floorId: string, tenantName?: string) {
    const normalizedTenantName = normalizeMapName(tenantName);
    const compactTenantName = normalizedTenantName.replace(/\s+/g, '');
    const mapConfig = getMapConfig(floorId);

    return mapConfig.tenants.find((mapTenant) =>
        mapTenant.keys.some((key) => {
            const normalizedKey = normalizeMapName(key);
            const compactKey = normalizedKey.replace(/\s+/g, '');

            return (
                normalizedTenantName.includes(normalizedKey) ||
                normalizedKey.includes(normalizedTenantName) ||
                compactTenantName.includes(compactKey) ||
                compactKey.includes(compactTenantName)
            );
        }),
    );
}

function getMapMarkerPercent(marker: MapTenantMarker | undefined, mapSize: MapConfig['size']) {
    if (!marker) {
        return undefined;
    }

    return {
        left: (marker.x / mapSize.width) * 100,
        top: (marker.y / mapSize.height) * 100,
    };
}

function getMapMarkerPosition(marker: MapTenantMarker | undefined, mapSize: MapConfig['size']) {
    const markerPercent = getMapMarkerPercent(marker, mapSize);

    if (!markerPercent) {
        return undefined;
    }

    return {
        left: `${markerPercent.left}%`,
        top: `${markerPercent.top}%`,
    };
}

function getMapTenantShape(marker: MapTenantMarker | undefined, mapConfig: MapConfig) {
    if (!marker) {
        return undefined;
    }

    if (marker.shapeId) {
        return mapConfig.shapes[marker.shapeId];
    }

    return mapConfig.shapes[`${marker.x}-${marker.y}`];
}

